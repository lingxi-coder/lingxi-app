/**
 * What Remote Control does with each engine event.
 *
 * - `forward`: sent to viewers as it happens, and kept in snapshots while the
 *   runtime keeps it in its replay buffer;
 * - `coalesce`: like `forward`, but adjacent deltas are merged into one;
 * - `state`: not part of the transcript. The latest copy is kept and sent in
 *   snapshots, and changes are sent as they happen. The base events
 *   (`session_started`, `session_resumed`) are here too: they are the
 *   snapshot's starting point, never a record, and a new one is a new epoch;
 * - `drop`: noise a viewer has no use for;
 * - `withheld`: never leaves the computer. Every event the desktop keeps to
 *   itself or does not apply to it, everything that can carry a credential, a
 *   setting or a path, and every answer to a request a viewer cannot make.
 *
 * Exhaustive: adding an engine event without deciding this fails to compile.
 */
export type RemoteEventDisposition = 'forward' | 'coalesce' | 'state' | 'drop' | 'withheld';

