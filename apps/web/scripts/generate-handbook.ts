import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { docGroups, docPages, docMarkdown } from '../src/data/docs';
import { docsBaseline, validateDocBaseline } from '../src/data/docs/sources';
import { preflightGeneratedPaths } from './export-files';

const webRoot = fileURLToPath(new URL('..', import.meta.url));
const output = path.resolve(webRoot, '../../docs/technical');
const check = process.argv.includes('--check');
if (process.argv.includes('--sources')) {
  process.stdout.write(JSON.stringify(docPages.map(({ id, sources }) => ({ id, sources }))));
} else if (process.argv.includes('--examples')) {
  process.stdout.write(JSON.stringify(docPages.flatMap((page) => page.sections.flatMap((section) => (section.code ?? []).map((block) => ({ ...block, page: page.id, group: page.group, section: section.id }))))));
} else {
  validateDocBaseline(docPages);
  for (const page of docPages) if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(page.id)) throw new Error(`Invalid page ID: ${page.id}`);
  const files = new Map<string, string | Buffer>();
  for (const locale of ['zh', 'en'] as const) {
    const index = [`# ${locale === 'zh' ? 'LingXi 技术手册' : 'LingXi technical handbook'}`,
      locale === 'zh' ? '当前工作区的双语系统与 SDK 文档。正文由官网文档数据生成，请在 apps/web/src/data/docs 修改。' : 'Bilingual system and SDK documentation for the current working tree. Generated from website documentation data; edit apps/web/src/data/docs.',
      `[${locale === 'zh' ? '英文目录' : 'Chinese contents'}](../${locale === 'zh' ? 'en' : 'zh'}/README.md)`];
    for (const group of docGroups) {
      const pages = docPages.filter((page) => page.group === group.id);
      if (!pages.length) continue;
      index.push(`## ${group.title[locale]}`);
      index.push(pages.map((page) => `- [${page.title[locale]}](${page.id}.md) — ${page.description[locale]}`).join('\n'));
    }
    files.set(`${locale}/README.md`, index.join('\n\n') + '\n');
    for (const page of docPages) files.set(`${locale}/${page.id}.md`, docMarkdown(page, locale) + '\n<!-- Generated from apps/web/src/data/docs. Do not edit this file directly. -->\n');
  }
  for (const page of docPages) for (const section of page.sections) {
    const source = section.diagram?.src;
    if (!source) continue;
    if (!source.startsWith('/docs-assets/') || source.includes('..')) throw new Error(`Invalid diagram: ${source}`);
    files.set(`assets/${source.slice('/docs-assets/'.length)}`, await readFile(path.join(webRoot, 'public', source.slice(1))));
  }
  files.set('baseline.json', JSON.stringify(docsBaseline, null, 2) + '\n');
  files.set('README.md', '# LingXi technical handbook / 技术手册\n\n- [中文](zh/README.md)\n- [English](en/README.md)\n\nGenerated from apps/web/src/data/docs. Run npm run docs:sync or npm run docs:check from apps/web.\n');
  const manifest = [...files.keys()].sort();
  const allowedRoot = path.resolve(webRoot, '../..');
  await preflightGeneratedPaths(output, [...manifest, '.generated-files.json'], allowedRoot);
  let previous: string[] = [];
  try { previous = JSON.parse(await readFile(path.join(output, '.generated-files.json'), 'utf8')); } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  if (!Array.isArray(previous) || !previous.every((relative) => typeof relative === 'string')) throw new Error('Invalid generated file ownership record');
  await preflightGeneratedPaths(output, previous, allowedRoot);
  const ownership = JSON.stringify(manifest, null, 2) + '\n';
  if (check) files.set('.generated-files.json', ownership);
  const differences: string[] = [];
  for (const [relative, content] of files) {
    const destination = path.join(output, relative);
    if (check) {
      let actual: Buffer | undefined;
      try { actual = await readFile(destination); } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
      if (!actual?.equals(Buffer.isBuffer(content) ? content : Buffer.from(content))) differences.push(relative);
    } else {
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, content);
    }
  }
  for (const stale of previous.filter((relative) => !manifest.includes(relative))) {
    if (check) differences.push(`obsolete: ${stale}`);
    else await rm(path.join(output, stale), { force: true });
  }
  // Catch new unregistered Markdown files rather than silently deleting them.
  if (check) for (const locale of ['zh', 'en']) {
    try { for (const name of await readdir(path.join(output, locale))) if (name.endsWith('.md') && !files.has(`${locale}/${name}`)) differences.push(`unregistered: ${locale}/${name}`); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  }
  if (!check) await writeFile(path.join(output, '.generated-files.json'), ownership);
  if (differences.length) throw new Error(`Handbook export is stale: ${differences.join(', ')}. Run npm run docs:sync`);
  process.stdout.write(`Handbook ${check ? 'checked' : 'generated'}: ${docPages.length} pages × 2 languages, ${manifest.length + 1} files\n`);
}
