import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import test from 'node:test';
import { docGroups, docPages, docMarkdown, searchDocs } from '../src/data/docs';
import { docsBaseline, resolveDocSources } from '../src/data/docs/sources';
import { markdownHref } from '../src/data/docs/markdown';
const web = fileURLToPath(new URL('..', import.meta.url));
const output = path.resolve(web, '../../docs/technical');

function bilingual(value: { en: string; zh: string }) {
  assert.ok(value.en.trim() && value.zh.trim(), 'Both language values must be substantive');
}

test('complete handbook covers core domains with actual sources and bilingual rich content', () => {
  const ids = new Set(docPages.map((page) => page.id));
  assert.equal(ids.size, docPages.length);
  assert.ok(docPages.length >= 40);
  for (const required of ['system-overview', 'development-workflow', 'harness', 'agent-execution', 'session-storage', 'configuration-security', 'extensions-lifecycle', 'agents-background', 'automation-workflows-fusion', 'llm-client', 'llm-audio', 'llm-files', 'llm-realtime', 'mobile-linux', 'bridge-client', 'desktop-host', 'cli-tui', 'web-product', 'build-release', 'validation-evidence', 'troubleshooting']) assert.ok(ids.has(required), required);
  for (const page of docPages) {
    assert.ok(docGroups.some((group) => group.id === page.group));
    assert.ok(page.sources?.length, page.id + ': source contract');
    assert.equal(resolveDocSources(page).length, page.sources?.length, page.id + ': saved provenance');
    for (const source of resolveDocSources(page)) {
      assert.match(source.revision, /^[0-9a-f]{40}$/u);
      if (source.sourceState === 'working-tree') assert.equal(source.url, undefined);
      else assert.ok(source.url?.includes(`/blob/${source.revision}/${source.path}`));
    }
    for (const section of page.sections) {
      for (const value of [...(section.paragraphs ?? []), ...(section.bullets ?? []), ...(section.steps ?? [])]) bilingual(value);
      for (const table of section.tables ?? []) {
        table.headers.forEach(bilingual);
        for (const row of table.rows) { assert.equal(row.length, table.headers.length); row.forEach(bilingual); }
      }
      for (const link of section.links ?? []) {
        bilingual(link.label);
        if (link.href.startsWith('/docs/')) {
          const [id, anchor] = link.href.slice('/docs/'.length).split('#');
          const destination = docPages.find((candidate) => candidate.id === id);
          assert.ok(destination, `${page.id}: ${link.href}`);
          if (anchor) assert.ok(destination.sections.some((candidate) => candidate.id === anchor), `${page.id}: ${link.href}`);
        }
      }
      if (section.diagram) {
        bilingual(section.diagram.alt);
        assert.ok(existsSync(path.join(web, 'public', section.diagram.src)), section.diagram.src);
        assert.ok(readFileSync(path.join(web, 'public', section.diagram.src), 'utf8').includes('<svg'));
      }
    }
  }
  for (const repository of docsBaseline.repositories) assert.match(repository.treeFingerprint, /^sha256:[0-9a-f]{64}$/u);
});

test('Markdown includes every shared content block, explicit anchor and source attribution', () => {
  for (const page of docPages) for (const locale of ['zh', 'en'] as const) {
    const markdown = docMarkdown(page, locale);
    for (const section of page.sections) {
      assert.ok(markdown.includes(`<a id="${section.id}"></a>`));
      for (const text of [...(section.paragraphs ?? []), ...(section.bullets ?? []), ...(section.steps ?? [])]) assert.ok(markdown.includes(text[locale]));
      for (const block of section.code ?? []) assert.ok(markdown.includes(block.code));
      for (const api of section.apis ?? []) assert.ok(markdown.includes(api.signature));
      for (const link of section.links ?? []) assert.ok(markdown.includes(`](${markdownHref(link.href)})`));
      if (section.diagram) assert.ok(markdown.includes(markdownHref(section.diagram.src)));
    }
    for (const source of resolveDocSources(page)) assert.ok(markdown.includes(source.repo + '/' + source.path));
    const saved = readFileSync(path.join(output, locale, page.id + '.md'), 'utf8');
    assert.equal(createHash('sha256').update(saved).digest('hex'), createHash('sha256').update(markdown + '\n<!-- Generated from apps/web/src/data/docs. Do not edit this file directly. -->\n').digest('hex'), `${locale}/${page.id}.md is stale`);
  }
});

test('generated content checks succeed without sibling SDK repositories', () => {
  const result = spawnSync(process.execPath, ['scripts/sync-docs.mjs', '--check', '--content-only', '--workspace', '/intentionally/absent/sdk/workspace'], { cwd: web, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stdout + result.stderr);
});

test('tables, steps and diagram descriptions participate in handbook search', () => {
  assert.ok(searchDocs('Unavailable', 'en').length);
  assert.ok(searchDocs('资源完整性', 'zh').length);
  assert.equal(markdownHref('/docs/harness#installation'), 'harness.md#installation');
  assert.equal(markdownHref('/docs-assets/system-layers.svg'), '../assets/system-layers.svg');
});
