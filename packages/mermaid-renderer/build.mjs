import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';

const root = new URL('../../', import.meta.url);
const lock = JSON.parse(await readFile(new URL('package-lock.json', import.meta.url), 'utf8'));
const notices = ['Third-party notices for the offline Mermaid renderer.\nThe official standalone bundle also retains upstream license annotations.\n'];
for (const path of Object.keys(lock.packages).filter((path) => path.startsWith('node_modules/')).sort()) {
  const directory = new URL(`${path}/`, import.meta.url);
  const metadata = JSON.parse(await readFile(new URL('package.json', directory), 'utf8'));
  notices.push(`\n${'='.repeat(72)}\n${metadata.name} ${metadata.version}\nLicense: ${metadata.license ?? 'see upstream notice'}\n`);
  for (const name of (await readdir(directory)).filter((name) => /^(license|copying|notice)(\.|$|_)/i.test(name)).sort()) {
    const text = await readFile(new URL(name, directory), 'utf8').catch((error) => {
      if (error.code === 'EISDIR') return '';
      throw error;
    });
    if (text) notices.push(`${name}\n${text}\n`);
  }
}
const notice = notices.join('\n');
// Use the official standalone distribution, including its bundled notices.
const engine = await readFile(new URL('node_modules/mermaid/dist/mermaid.min.js', import.meta.url), 'utf8');
const viewer = await readFile(new URL('viewer.js', import.meta.url), 'utf8');
const script = `${engine}\n;(() => {\n${viewer}\n})();`.replace(/<\/script/gi, '<\\/script');
const hash = createHash('sha256').update(script).digest('base64');
const style = await readFile(new URL('viewer.css', import.meta.url), 'utf8');
const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'sha256-${hash}'; style-src 'unsafe-inline'; img-src data:; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'">
<!-- Generated by packages/mermaid-renderer/build.mjs.
${notice.replace(/--/g, '- -')}
-->
<style>${style}</style></head><body>
<nav aria-label="Diagram"><button id="out" aria-label="Zoom out">−</button><button id="in" aria-label="Zoom in">+</button><button id="fit" aria-label="Reset zoom">↺</button><button id="source" aria-label="Source code">&lt;/&gt;</button></nav>
<p id="error" role="status" hidden></p><main id="viewport"><div id="diagram" role="img" aria-label="Mermaid diagram"></div><pre id="code" hidden></pre></main>
<script>${script}</script></body></html>\n`;
const output = new URL('resources/mermaid/mermaid.html', root);
const noticeOutput = new URL('resources/mermaid/THIRD_PARTY_NOTICES.txt', root);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== html) throw new Error('Mermaid resource is stale; run npm run build');
  if (await readFile(noticeOutput, 'utf8') !== notice) throw new Error('Mermaid notices are stale');
} else {
  await mkdir(new URL('resources/mermaid/', root), { recursive: true });
  await writeFile(output, html);
  await writeFile(noticeOutput, notice);
}
console.log(`Mermaid offline renderer: ${Buffer.byteLength(html)} bytes`);
