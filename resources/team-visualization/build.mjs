import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const opts = { absWorkingDir: root, bundle: true, minify: true, legalComments: 'inline',
  write: false, charset: 'ascii', target: 'es2020', format: 'iife', platform: 'browser' };
const guest = (await build({ ...opts, entryPoints: ['guest.js'] })).outputFiles[0].text;
const worker = (await build({ ...opts, entryPoints: ['worker.js'],
  define: { LINGXI_GUEST: JSON.stringify(guest) } })).outputFiles[0].text;
const surface = (await build({ ...opts, entryPoints: ['surface.js'],
  define: { LINGXI_WORKER: JSON.stringify(worker) } })).outputFiles[0].text;
const theme = await readFile(new URL('theme.css', import.meta.url), 'utf8');
const doc = `<!doctype html>
<!-- Generated by resources/team-visualization/build.mjs. -->
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval'; style-src 'unsafe-inline'; img-src data:; worker-src blob:; connect-src 'none'; frame-src 'none'; form-action 'none'; base-uri 'none'; object-src 'none'">
<style>${theme}</style></head><body><main id="surface"></main><script>${surface.replace(/<\/script/giu, '<\\/script')}</script></body></html>\n`;
const output = new URL('assets/team-visualization.html', import.meta.url);
if (process.argv.includes('--check')) {
  if (doc !== await readFile(output, 'utf8')) throw new Error('Team visualization bundle needs regeneration');
} else {
  await mkdir(new URL('assets/', import.meta.url), { recursive: true });
  await writeFile(output, doc);
}
